'use strict';

function formater(montant) {
    const nombre = String(montant).replace(/\D/g, '');
    const avecEspaces = nombre.replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
    return `${avecEspaces} MAD`;
}

console.log(formater(1234567));
