'use strict';

function validerPlaque(plaque) {
    return /^\d{4,5}-[A-Z]{1,2}-\d{1,2}$/.test(plaque);
}

console.log(validerPlaque('1234-A-56'));
console.log(validerPlaque('12345-AB-6'));
