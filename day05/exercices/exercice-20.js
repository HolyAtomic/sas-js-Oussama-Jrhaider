'use strict';

function genererSlug(texte) {
    return texte
        .toLowerCase()
        .normalize('NFD')
        .replace(/[̀-ͯ]/g, '')
        .replace(/[^a-z0-9\s-]/g, '')
        .trim()
        .replace(/\s+/g, '-');
}

console.log(genererSlug('Les 10 secrets de JavaScript !'));
